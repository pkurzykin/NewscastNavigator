const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const project = path.resolve(__dirname, '../../..');
const req = createRequire(path.join(project, 'frontend/package.json'));
const React = req('react');
const { renderToStaticMarkup } = req('react-dom/server');
const { transformSync } = req('esbuild');
const { JSDOM } = req('jsdom');
const base = path.join(project, 'artifacts/design/2026-09-06-paper-scenario/approved-baseline');
const source = fs.readFileSync(path.join(base, 'paper-export.jsx'), 'utf8');
const transformed = transformSync('const Preview = () => ' + source + '; module.exports = Preview;', { loader: 'jsx', format: 'cjs' }).code;
const moduleObject = { exports: {} };
new Function('React', 'module', 'exports', transformed)(React, moduleObject, moduleObject.exports);
const baselineMarkup = renderToStaticMarkup(React.createElement(moduleObject.exports));
const doc = new JSDOM(baselineMarkup).window.document;
const root = doc.body.firstElementChild;
const children = [...root.children];
const shell = children.slice(0, 4).map((el, i) => {
  el.classList.add('source-shell', ['app-nav', 'story-heading', 'story-tabs', 'workflow'][i]);
  return el.outerHTML;
}).join('\n');
const tokens = fs.readFileSync(path.join(base, 'tokens.css'), 'utf8');
const fontData = fs.readFileSync(path.join(project, 'frontend/public/fonts/onest/Onest-VariableFont.woff2')).toString('base64');
const font = `@font-face{font-family:Onest;src:url(data:font/woff2;base64,${fontData}) format('woff2');font-weight:100 900;font-style:normal;font-display:swap}`;
fs.writeFileSync(path.join(__dirname, 'baseline.html'), `<!doctype html><html lang="ru"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Прежний макет редактора</title><style>${tokens}${font}body{margin:0;background:var(--color-canvas)}body>div{margin:auto}</style>${baselineMarkup}</html>`);
const head = fs.readFileSync(path.join(__dirname, 'preview-shell.html'), 'utf8');
fs.writeFileSync(path.join(__dirname, 'index.html'), head.replace('<!-- SHARED_STYLE -->', `<style>${tokens}${font}</style>`).replace('<!-- ORIGINAL_SHELL -->', shell));
console.log('Local preview built from saved Paper JSX; no application files changed.');
